/**
 * OpenLore daemon supervisor — global, works in every project.
 *
 * Why this exists: the openlore Pi extension spawns its daemon with
 * `process.execPath`, which under Pi-Bolt is the compiled `pi-bolt` binary
 * rather than `node`. Every spawn (and every `/openlore restart`) therefore
 * dies with `Error: Unknown options: --directory, --preset`, and the footer
 * stays on "daemon unavailable" while `.openlore/serve.log` fills up.
 *
 * This extension takes ownership of the daemon lifecycle instead:
 *   - on session_start, if the project has an `.openlore/` directory, make sure
 *     a daemon is serving that directory, supervised by a systemd user unit;
 *   - units are created per project, on demand, and never enabled at boot
 *     (a session is what asks for a daemon);
 *   - `pi.spawnDaemon: false` is merged into the project config so the broken
 *     native spawn path is never attempted;
 *   - `/openlore-daemon status|start|stop|restart` replaces the unusable
 *     `/openlore restart`.
 *
 * The openlore extension still finds the daemon by itself: it reads
 * `.openlore/serve.json`, validates `/health`, and adopts it on the next tool
 * call. After a port change the first tool call may report ECONNREFUSED once —
 * that is its re-adopt path, retry and it connects.
 */

import * as crypto from "node:crypto";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import type { ExtensionAPI, ExtensionContext } from "@earendil-works/pi-coding-agent";

const UNIT_DIR = path.join(os.homedir(), ".config", "systemd", "user");
const DEFAULT_BIN = path.join(os.homedir(), ".npm-global", "bin", "openlore");
const START_TIMEOUT_MS = 15_000;

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

/** Deterministic, readable, collision-free unit name for a project directory. */
function unitNameFor(projectDir: string): string {
	const abs = path.resolve(projectDir);
	const readable =
		abs
			.replace(/^\/+/, "")
			.replace(/[^A-Za-z0-9]+/g, "-")
			.replace(/^-+|-+$/g, "")
			.slice(0, 60)
			.replace(/-+$/g, "") || "root";
	const hash = crypto.createHash("sha1").update(abs).digest("hex").slice(0, 8);
	return `openlore-${readable}-${hash}`;
}

function unitPathFor(unit: string): string {
	return path.join(UNIT_DIR, `${unit}.service`);
}

function unitBody(bin: string, projectDir: string): string {
	return `[Unit]
Description=OpenLore daemon for ${projectDir}
Documentation=https://github.com/clay-good/OpenLore
# Generated by the pi openlore-supervisor extension; rewritten when it drifts.

[Service]
Type=simple
WorkingDirectory=${projectDir}
ExecStart=${bin} serve --directory ${projectDir} --preset full --idle-timeout 0
Restart=on-failure
RestartSec=5s

[Install]
WantedBy=default.target
`;
}

function readJson(file: string): any | null {
	try {
		return JSON.parse(fs.readFileSync(file, "utf8"));
	} catch {
		return null;
	}
}

function isAlive(pid: number): boolean {
	try {
		process.kill(pid, 0);
		return true;
	} catch (err: any) {
		// EPERM means the process exists but belongs to someone else.
		return err?.code === "EPERM";
	}
}

/** PID of a live daemon for this project, or null. */
function runningPid(projectDir: string): number | null {
	const descriptor = readJson(path.join(projectDir, ".openlore", "serve.json"));
	const pid = Number(descriptor?.pid);
	return Number.isFinite(pid) && pid > 0 && isAlive(pid) ? pid : null;
}

function daemonPort(projectDir: string): number | null {
	const descriptor = readJson(path.join(projectDir, ".openlore", "serve.json"));
	const port = Number(descriptor?.port);
	return Number.isFinite(port) && port > 0 ? port : null;
}

/** Stop the extension's own spawn attempts; they cannot work under Pi-Bolt. */
function disableNativeSpawn(projectDir: string): void {
	const configPath = path.join(projectDir, ".openlore", "config.json");
	const config = readJson(configPath);
	if (!config || config?.pi?.spawnDaemon === false) return;
	config.pi = { ...(config.pi ?? {}), spawnDaemon: false };
	try {
		fs.writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`, "utf8");
	} catch {
		/* read-only config: not fatal, the supervisor still works */
	}
}

async function resolveBinary(pi: ExtensionAPI): Promise<string | null> {
	const override = process.env.OPENLORE_BIN;
	if (override && fs.existsSync(override)) return override;
	const which = await pi.exec("bash", ["-lc", "command -v openlore"], { timeout: 5000 });
	const found = which.code === 0 ? which.stdout.trim().split("\n")[0] : "";
	if (found && fs.existsSync(found)) return found;
	return fs.existsSync(DEFAULT_BIN) ? DEFAULT_BIN : null;
}

type Outcome = { started: boolean; ok: boolean; detail: string };

async function ensureDaemon(pi: ExtensionAPI, projectDir: string): Promise<Outcome> {
	const abs = path.resolve(projectDir);
	if (!fs.existsSync(path.join(abs, ".openlore"))) {
		return { started: false, ok: false, detail: "not an OpenLore project (no .openlore/)" };
	}

	disableNativeSpawn(abs);

	const existing = runningPid(abs);
	if (existing) {
		return { started: false, ok: true, detail: `already up (pid ${existing})` };
	}

	const bin = await resolveBinary(pi);
	if (!bin) {
		return { started: false, ok: false, detail: "the openlore CLI was not found (set OPENLORE_BIN)" };
	}

	const unit = unitNameFor(abs);
	const file = unitPathFor(unit);
	const wanted = unitBody(bin, abs);
	let wrote = false;
	try {
		const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
		if (current !== wanted) {
			fs.mkdirSync(UNIT_DIR, { recursive: true });
			fs.writeFileSync(file, wanted, "utf8");
			wrote = true;
		}
	} catch (err: any) {
		return { started: false, ok: false, detail: `cannot write ${file}: ${err?.message ?? err}` };
	}

	if (wrote) {
		await pi.exec("systemctl", ["--user", "daemon-reload"], { timeout: 15_000 });
	}

	const start = await pi.exec("systemctl", ["--user", "start", `${unit}.service`], { timeout: 30_000 });
	if (start.code !== 0) {
		const why = `${start.stderr}\n${start.stdout}`.trim().split("\n").filter(Boolean).slice(-3).join(" | ");
		return { started: false, ok: false, detail: `systemctl start ${unit} failed: ${why || `exit ${start.code}`}` };
	}

	const deadline = Date.now() + START_TIMEOUT_MS;
	while (Date.now() < deadline) {
		const pid = runningPid(abs);
		if (pid) return { started: true, ok: true, detail: `started pid ${pid} on port ${daemonPort(abs) ?? "?"} (${unit})` };
		await sleep(400);
	}
	return {
		started: false,
		ok: false,
		detail: `${unit} started but no live daemon appeared; check journalctl --user -u ${unit}`,
	};
}

export default function (pi: ExtensionAPI) {
	pi.on("session_start", async (_event, ctx) => {
		const outcome = await ensureDaemon(pi, ctx.cwd).catch((err: any) => ({
			started: false,
			ok: false,
			detail: `supervisor error: ${err?.message ?? err}`,
		}));
		// Stay quiet in projects that do not use OpenLore, and when a daemon was
		// already running — noise on every session start is worse than silence.
		if (!outcome.ok) {
			const quiet = outcome.detail.startsWith("not an OpenLore project");
			if (!quiet) ctx.ui.notify(`openlore: ${outcome.detail}`, "warning");
		} else if (outcome.started) {
			ctx.ui.notify(`openlore: ${outcome.detail}`, "info");
		}
	});

	pi.registerCommand("openlore-daemon", {
		description: "Supervise this project's OpenLore daemon (status|start|stop|restart)",
		handler: async (args: string, ctx: ExtensionContext) => {
			const action = (args ?? "").trim().split(/\s+/)[0] || "status";
			const abs = path.resolve(ctx.cwd);
			const unit = unitNameFor(abs);

			if (!fs.existsSync(path.join(abs, ".openlore"))) {
				ctx.ui.notify(`${abs} has no .openlore/ — nothing to supervise`, "warning");
				return;
			}

			if (action === "status") {
				const pid = runningPid(abs);
				const state = await pi.exec("systemctl", ["--user", "is-active", `${unit}.service`], { timeout: 10_000 });
				ctx.ui.notify(
					pid
						? `openlore: pid ${pid} on port ${daemonPort(abs) ?? "?"} · ${unit} · ${state.stdout.trim() || "unknown"}`
						: `openlore: no live daemon · ${unit} · ${state.stdout.trim() || "unknown"} — run /openlore-daemon start`,
					pid ? "info" : "warning",
				);
				return;
			}

			if (action === "stop") {
				const stop = await pi.exec("systemctl", ["--user", "stop", `${unit}.service`], { timeout: 30_000 });
				ctx.ui.notify(
					stop.code === 0 ? `openlore: ${unit} stopped` : `openlore: stop failed — ${stop.stderr.trim()}`,
					stop.code === 0 ? "info" : "error",
				);
				return;
			}

			if (action === "restart") {
				await pi.exec("systemctl", ["--user", "stop", `${unit}.service`], { timeout: 30_000 });
				const outcome = await ensureDaemon(pi, abs);
				ctx.ui.notify(`openlore: ${outcome.detail}`, outcome.ok ? "info" : "error");
				return;
			}

			if (action === "start") {
				const outcome = await ensureDaemon(pi, abs);
				ctx.ui.notify(`openlore: ${outcome.detail}`, outcome.ok ? "info" : "error");
				return;
			}

			ctx.ui.notify(`openlore-daemon: unknown action "${action}" (status|start|stop|restart)`, "warning");
		},
	});
}
